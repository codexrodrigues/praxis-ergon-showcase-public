      DATE '1998-01-01',DATE '1999-12-31',2,'Empregador anterior','RGPS','RGPS','APOSENTADORIA',730,730,90,
      DATE '2026-06-01','Retirada parcial de tempo conforme revisão da certidão');
    FOR ordem IN 1..3 LOOP
      INSERT INTO periodos_aquisitivos_licenca_especial(emp_codigo,numfunc,numvinc,descricao,dtini,dtfim,chave,
        dias_direito,dias_gozados,dias_vendidos,dias_convertidos_dobro,saldo_dias,dt_prescricao,dt_cnt_dobro,
        anos_lic_esp,meses_lic_esp_per,abono_dir_gozo_lic_esp,num_dias_abono_lic_esp,den_dias_abono_lic_esp,
        vend_lic_esp,min_dias_pvend_lic_esp,max_dias_vend_lic_esp,cont_dobro_lic_esp,
        min_dias_pcont_dob_lic_esp,max_dias_cont_dob_lic_esp,perm_gozo_lic_esp_ant_fim_pe,averbacao_origem_id,observacoes)
      VALUES(titular.emp_codigo,titular.numfunc,titular.numero,'Quinquênio demonstrativo ' || ordem,
