        (DATE '2010-12-31' + (ordem-1)*INTERVAL '5 years')::DATE,ordem,
        90,CASE WHEN ordem=1 THEN 45 ELSE 0 END,CASE WHEN ordem=1 THEN 15 ELSE 0 END,
        CASE WHEN ordem=2 THEN 30 ELSE 0 END,CASE WHEN ordem=1 THEN 30 WHEN ordem=2 THEN 60 ELSE 90 END,
        CASE WHEN ordem=3 THEN DATE '2026-12-15' ELSE DATE '2028-12-31' END,
        CASE WHEN ordem=2 THEN DATE '2026-04-01' END,
        5,3,CASE WHEN ordem=1 THEN 'G' ELSE 'D' END,1,3,CASE WHEN ordem=3 THEN 'N' ELSE 'S' END,5,30,
        CASE WHEN ordem=2 THEN 'S' ELSE 'I' END,15,60,
        CASE WHEN ordem=3 THEN TRUE WHEN ordem=2 THEN FALSE END,
        CASE WHEN ordem=1 THEN averbacao END,
        'Cenário sintético: precedência individual (39127/58337/58924/82601) e antecipação (103339)')
      RETURNING id INTO ciclo;
      IF ordem=1 THEN
        INSERT INTO licencas_especiais_gozo(emp_codigo,numfunc,numvinc,descricao,dtini,dtfim,
          periodo_aquisitivo_licenca_id,chave_peraqlicesp,ordem_parcela,dtprevfim,dias_gozo)
