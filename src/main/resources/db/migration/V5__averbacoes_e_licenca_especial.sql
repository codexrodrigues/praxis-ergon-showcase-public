      'LICENCA_ESPECIAL','01012006-31122010',DATE '2006-01-01',1826,90,'Tempo de origem do primeiro ciclo demonstrativo')
    RETURNING id INTO averbacao;
    INSERT INTO averbacoes_tempo_servico(emp_codigo,numfunc,numvinc,descricao,dtini,dtfim,chave,
      instituicao,tipo_tempo,regime_previdenciario,finalidade,total_dias,dias_finalidade,dias_desaverbados,data_desaverbacao,motivo_desaverbacao)
