CREATE TABLE averbacoes_tempo_servico (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  emp_codigo INTEGER NOT NULL REFERENCES empresas(empresa),
  numfunc BIGINT NOT NULL REFERENCES funcionarios(numero), numvinc INTEGER NOT NULL,
  descricao VARCHAR(200) NOT NULL, dtini DATE NOT NULL, dtfim DATE,
  situacao VARCHAR(30) NOT NULL DEFAULT 'REGISTRADO' CHECK (situacao IN ('REGISTRADO','CANCELADO')),
  documento_legal_id BIGINT REFERENCES documentos_legais(id),
  ato_publicacao_id BIGINT REFERENCES documentos_legais(id), observacoes VARCHAR(2000),
  chave INTEGER NOT NULL, instituicao VARCHAR(200),
  tipo_tempo VARCHAR(30) NOT NULL CHECK (tipo_tempo IN ('PUBLICO','RGPS')),
  regime_previdenciario VARCHAR(20),
  finalidade VARCHAR(30) NOT NULL CHECK (finalidade IN ('APOSENTADORIA','LICENCA_ESPECIAL','TEMPO_SERVICO')),
  complemento VARCHAR(20), data_a_contar DATE, total_dias INTEGER NOT NULL CHECK (total_dias >= 0),
  dias_finalidade INTEGER NOT NULL CHECK (dias_finalidade >= 0),
  sobrepoe BOOLEAN NOT NULL DEFAULT FALSE, motivo VARCHAR(2000),
  data_remocao DATE, motivo_remocao VARCHAR(2000),
  dias_desaverbados INTEGER NOT NULL DEFAULT 0 CHECK (dias_desaverbados >= 0 AND dias_desaverbados <= total_dias),
  data_desaverbacao DATE, motivo_desaverbacao VARCHAR(2000), info1 VARCHAR(2000), info2 VARCHAR(2000),
  referencia_anexo VARCHAR(255), custom_fields JSONB NOT NULL DEFAULT '{}',
  version BIGINT NOT NULL DEFAULT 0,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP, updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (numfunc,numvinc) REFERENCES vinculos(numfunc,numero),
  UNIQUE(emp_codigo,numfunc,numvinc,chave,finalidade),
  UNIQUE(id,emp_codigo,numfunc,numvinc),
  CHECK (dtfim IS NULL OR dtfim >= dtini)
);

CREATE TABLE periodos_aquisitivos_licenca_especial (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  emp_codigo INTEGER NOT NULL REFERENCES empresas(empresa),
  numfunc BIGINT NOT NULL REFERENCES funcionarios(numero), numvinc INTEGER NOT NULL,
  descricao VARCHAR(200) NOT NULL, dtini DATE NOT NULL, dtfim DATE,
  situacao VARCHAR(30) NOT NULL DEFAULT 'REGISTRADO' CHECK (situacao IN ('REGISTRADO','CANCELADO')),
  documento_legal_id BIGINT REFERENCES documentos_legais(id),
  ato_publicacao_id BIGINT REFERENCES documentos_legais(id), observacoes VARCHAR(2000),
  chave INTEGER NOT NULL, dias_direito INTEGER NOT NULL DEFAULT 90 CHECK (dias_direito BETWEEN 0 AND 999),
  dias_gozados INTEGER NOT NULL DEFAULT 0 CHECK (dias_gozados >= 0),
  dias_vendidos INTEGER NOT NULL DEFAULT 0 CHECK (dias_vendidos >= 0),
  dias_convertidos_dobro INTEGER NOT NULL DEFAULT 0 CHECK (dias_convertidos_dobro >= 0),
  saldo_dias INTEGER NOT NULL DEFAULT 90 CHECK (saldo_dias >= 0),
  dt_prescricao DATE, dt_cnt_dobro DATE, anos_lic_esp INTEGER CHECK (anos_lic_esp BETWEEN 1 AND 99),
  meses_lic_esp_per INTEGER CHECK (meses_lic_esp_per BETWEEN 1 AND 99),
  abono_dir_gozo_lic_esp VARCHAR(1) CHECK (abono_dir_gozo_lic_esp IN ('D','G','N')),
  num_dias_abono_lic_esp INTEGER CHECK (num_dias_abono_lic_esp >= 0),
  den_dias_abono_lic_esp INTEGER CHECK (den_dias_abono_lic_esp > 0),
  vend_lic_esp VARCHAR(1) DEFAULT 'I' CHECK (vend_lic_esp IN ('I','S','N')),
  min_dias_pvend_lic_esp INTEGER CHECK (min_dias_pvend_lic_esp > 0),
  max_dias_vend_lic_esp INTEGER CHECK (max_dias_vend_lic_esp >= 0),
  cont_dobro_lic_esp VARCHAR(1) DEFAULT 'I' CHECK (cont_dobro_lic_esp IN ('I','S','N')),
  min_dias_pcont_dob_lic_esp INTEGER CHECK (min_dias_pcont_dob_lic_esp > 0),
  max_dias_cont_dob_lic_esp INTEGER CHECK (max_dias_cont_dob_lic_esp >= 0),
  perm_gozo_lic_esp_ant_fim_pe BOOLEAN,
  averbacao_origem_id BIGINT, referencia_anexo VARCHAR(255), custom_fields JSONB NOT NULL DEFAULT '{}',
  version BIGINT NOT NULL DEFAULT 0,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP, updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (numfunc,numvinc) REFERENCES vinculos(numfunc,numero),
  FOREIGN KEY (averbacao_origem_id,emp_codigo,numfunc,numvinc)
    REFERENCES averbacoes_tempo_servico(id,emp_codigo,numfunc,numvinc),
  UNIQUE(emp_codigo,numfunc,numvinc,chave), UNIQUE(id,emp_codigo,numfunc,numvinc,chave),
  CHECK (dtfim IS NULL OR dtfim >= dtini),
  CHECK (saldo_dias = dias_direito - dias_gozados - dias_vendidos - dias_convertidos_dobro)
);

CREATE TABLE licencas_especiais_gozo (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  emp_codigo INTEGER NOT NULL REFERENCES empresas(empresa),
  numfunc BIGINT NOT NULL REFERENCES funcionarios(numero), numvinc INTEGER NOT NULL,
  descricao VARCHAR(200) NOT NULL, dtini DATE NOT NULL, dtfim DATE,
  situacao VARCHAR(30) NOT NULL DEFAULT 'REGISTRADO' CHECK (situacao IN ('REGISTRADO','CANCELADO')),
  documento_legal_id BIGINT REFERENCES documentos_legais(id),
  ato_publicacao_id BIGINT REFERENCES documentos_legais(id), observacoes VARCHAR(2000),
  periodo_aquisitivo_licenca_id BIGINT NOT NULL, chave_peraqlicesp INTEGER NOT NULL,
  ordem_parcela INTEGER NOT NULL CHECK (ordem_parcela > 0), dtprevfim DATE NOT NULL,
  dias_gozo INTEGER NOT NULL CHECK (dias_gozo BETWEEN 1 AND 999),
  abono_pecuniario BOOLEAN NOT NULL DEFAULT FALSE, dias_abono INTEGER NOT NULL DEFAULT 0 CHECK (dias_abono >= 0),
  ini_fim_abono VARCHAR(1) CHECK (ini_fim_abono IN ('I','F')), mes_ano_folha DATE, num_folha INTEGER,
  custom_fields JSONB NOT NULL DEFAULT '{}', version BIGINT NOT NULL DEFAULT 0,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP, updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (numfunc,numvinc) REFERENCES vinculos(numfunc,numero),
  FOREIGN KEY (periodo_aquisitivo_licenca_id,emp_codigo,numfunc,numvinc,chave_peraqlicesp)
    REFERENCES periodos_aquisitivos_licenca_especial(id,emp_codigo,numfunc,numvinc,chave),
  UNIQUE(periodo_aquisitivo_licenca_id,ordem_parcela),
  CHECK (dtfim IS NULL OR dtfim >= dtini), CHECK (dtprevfim >= dtini)
);

CREATE TABLE vendas_licenca_especial (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  emp_codigo INTEGER NOT NULL REFERENCES empresas(empresa),
  numfunc BIGINT NOT NULL REFERENCES funcionarios(numero), numvinc INTEGER NOT NULL,
  descricao VARCHAR(200) NOT NULL, dtini DATE NOT NULL, dtfim DATE,
  situacao VARCHAR(30) NOT NULL DEFAULT 'REGISTRADO' CHECK (situacao IN ('REGISTRADO','CANCELADO')),
  documento_legal_id BIGINT REFERENCES documentos_legais(id),
  ato_publicacao_id BIGINT REFERENCES documentos_legais(id), observacoes VARCHAR(2000),
  periodo_aquisitivo_licenca_id BIGINT NOT NULL, chave_peraqlicesp INTEGER NOT NULL,
  dias_vendidos INTEGER NOT NULL CHECK (dias_vendidos BETWEEN 1 AND 999), dt_pagamento DATE,
  valor_indenizacao NUMERIC(15,2) CHECK (valor_indenizacao >= 0),
  modalidade VARCHAR(20) NOT NULL DEFAULT 'PECUNIA' CHECK (modalidade IN ('PECUNIA','ABONO')),
  mes_ano_folha DATE, num_folha INTEGER, custom_fields JSONB NOT NULL DEFAULT '{}', version BIGINT NOT NULL DEFAULT 0,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP, updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (numfunc,numvinc) REFERENCES vinculos(numfunc,numero),
  FOREIGN KEY (periodo_aquisitivo_licenca_id,emp_codigo,numfunc,numvinc,chave_peraqlicesp)
    REFERENCES periodos_aquisitivos_licenca_especial(id,emp_codigo,numfunc,numvinc,chave),
  CHECK (dtfim IS NULL OR dtfim >= dtini)
);

CREATE INDEX ix_averbacao_vinculo ON averbacoes_tempo_servico(emp_codigo,numfunc,numvinc);
