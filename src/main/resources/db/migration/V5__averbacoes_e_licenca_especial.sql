CREATE INDEX ix_venda_licenca_periodo ON vendas_licenca_especial(periodo_aquisitivo_licenca_id,dt_pagamento);
CREATE INDEX ix_venda_licenca_tenant ON vendas_licenca_especial(emp_codigo,numfunc,numvinc);

