DO $$
DECLARE
  titular RECORD; averbacao BIGINT; ciclo BIGINT; ordem INTEGER;
BEGIN
  FOR titular IN SELECT emp_codigo,numfunc,numero FROM vinculos
                 WHERE emp_codigo IS NOT NULL ORDER BY emp_codigo,numfunc,numero LIMIT 6 LOOP
    INSERT INTO averbacoes_tempo_servico(emp_codigo,numfunc,numvinc,descricao,dtini,dtfim,chave,
