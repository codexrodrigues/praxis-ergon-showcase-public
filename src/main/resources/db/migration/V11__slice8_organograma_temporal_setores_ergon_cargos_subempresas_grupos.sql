-- Encadeamento por identidade exata e mesma empresa; caminho usa segmentos hexadecimais
-- delimitados, portanto códigos com '/', '%', '_' ou prefixos irmãos não colidem.
CREATE FUNCTION organograma_em(p_org INTEGER,p_data DATE,p_hierarquia INTEGER DEFAULT 0)
RETURNS TABLE(periodo_id BIGINT,setor VARCHAR,nome VARCHAR,pai VARCHAR,caminho TEXT,nivel INTEGER,filhos BIGINT)
LANGUAGE sql STABLE AS $$
 WITH RECURSIVE vigentes AS (
  SELECT h.*, CASE p_hierarquia WHEN 0 THEN setor_pai WHEN 1 THEN setor_pai_hier1
   WHEN 2 THEN setor_pai_hier2 WHEN 3 THEN setor_pai_hier3 WHEN 4 THEN setor_pai_hier4 END AS pai_escolhido
  FROM historico_setores h WHERE emp_codigo=p_org AND p_hierarquia BETWEEN 0 AND 4
   AND dtini<=p_data AND (dtfim IS NULL OR dtfim>=p_data)
 ), arvore AS (
  SELECT h.id,h.setor,h.nome,h.pai_escolhido,
   ('/'||encode(convert_to(h.setor,'UTF8'),'hex')||'/')::TEXT AS caminho,
   1 AS nivel, ARRAY[h.setor::TEXT] AS visitados
  FROM vigentes h WHERE h.pai_escolhido IS NULL
  UNION ALL
  SELECT h.id,h.setor,h.nome,h.pai_escolhido,
   a.caminho||encode(convert_to(h.setor,'UTF8'),'hex')||'/', a.nivel+1, a.visitados||h.setor::TEXT
  FROM vigentes h JOIN arvore a ON h.pai_escolhido=a.setor
  WHERE NOT h.setor=ANY(a.visitados)
 ) SELECT a.id,a.setor,a.nome,a.pai_escolhido,a.caminho,a.nivel,
   (SELECT count(*) FROM vigentes f WHERE f.pai_escolhido=a.setor)
 FROM arvore a;
$$;

