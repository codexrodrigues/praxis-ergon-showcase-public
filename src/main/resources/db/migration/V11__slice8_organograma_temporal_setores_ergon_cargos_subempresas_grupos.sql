 UNION SELECT emp_codigo,dtfim+1 FROM setores_ergon WHERE dtfim IS NOT NULL
 UNION SELECT f.emp_codigo,f.dtini FROM funcoes_confianca f
  WHERE EXISTS (SELECT 1 FROM setores_ergon e WHERE e.emp_codigo=f.emp_codigo AND e.funcao_chefe_id=f.id)
 UNION SELECT f.emp_codigo,f.dtfim+1 FROM funcoes_confianca f
  WHERE f.dtfim IS NOT NULL
    AND EXISTS (SELECT 1 FROM setores_ergon e WHERE e.emp_codigo=f.emp_codigo AND e.funcao_chefe_id=f.id)
 UNION SELECT emp_codigo,dtini FROM cargos_setor
 UNION SELECT emp_codigo,dtfim+1 FROM cargos_setor WHERE dtfim IS NOT NULL
 UNION SELECT emp_codigo,dtini FROM designacoes_funcao
 UNION SELECT emp_codigo,dt_exercicio FROM designacoes_funcao WHERE dt_exercicio IS NOT NULL
 UNION SELECT emp_codigo,dtfim+1 FROM designacoes_funcao WHERE dtfim IS NOT NULL
 UNION SELECT emp_codigo,dtini FROM substituicoes_funcao
 UNION SELECT emp_codigo,dtfim+1 FROM substituicoes_funcao
 UNION SELECT emp_codigo,dtini FROM organograma_impedimentos
 UNION SELECT emp_codigo,dtfim+1 FROM organograma_impedimentos WHERE dtfim IS NOT NULL
), periodos AS (
 SELECT emp_codigo,dia,lead(dia) OVER(PARTITION BY emp_codigo ORDER BY dia)-1 AS fim FROM limites
)
SELECT h.id::text||':'||p.dia::text||':'||k.tipo::text AS id,
 h.id AS periodo_id,h.emp_codigo,h.setor,h.nome AS nome_setor,h.sigla AS sigla_setor,h.tipo_setor,
 a.pai AS setor_pai,h.setor_pai_hier1,h.setor_pai_hier2,h.setor_pai_hier3,h.setor_pai_hier4,
 a.caminho AS caminho_hierarquico,a.nivel AS nivel_hierarquico,a.filhos AS quantidade_subordinados_diretos,
 k.tipo AS tipo_hierarquia,p.dia AS dtini,p.fim AS dtfim,h.extinto,h.setor_substituto,
 h.subemp_codigo,h.localidade_codigo,e.centro_custo,e.cargo_chefe_id,e.funcao_chefe_id,
 comando.titular_numfunc AS chefe_titular_numfunc,comando.titular_numvinc AS chefe_titular_numvinc,comando.titular_nome AS chefe_titular_nome,
 comando.exercicio_numfunc AS chefe_em_exercicio_numfunc,comando.exercicio_numvinc AS chefe_em_exercicio_numvinc,comando.exercicio_nome AS chefe_em_exercicio_nome,
 comando.motivo::varchar AS motivo_ausencia_titular,comando.situacao::varchar AS situacao_comando_setor,
 NULL::bigint AS lotados_provimento_count,NULL::bigint AS em_exercicio_fisico_no_setor_count,
 NULL::bigint AS cedidos_para_outros_setores_count,NULL::bigint AS recebidos_de_outros_setores_count,
 NULL::bigint AS apropriados_folha_setor_count,
 (SELECT sum(c.lotacao_maxima_autorizada) FROM cargos_setor c WHERE c.emp_codigo=h.emp_codigo
   AND c.setor=h.setor AND c.dtini<=p.dia AND (c.dtfim IS NULL OR c.dtfim>=p.dia)
   AND NOT c.abrange_subordinados)::bigint AS vagas_autorizadas_setor,
 NULL::bigint AS vagas_ocupadas_setor,NULL::numeric AS percentual_cobertura_chefia_subarvore,
 'ESTRUTURA_E_COMANDO_POR_FUNCAO;PROVIMENTO_EXERCICIO_FOLHA_E_COMANDO_POR_CARGO_NAO_INTEGRADOS'::varchar AS escopo_apuracao
FROM periodos p CROSS JOIN generate_series(0,4) k(tipo)
CROSS JOIN LATERAL organograma_em(p.emp_codigo,p.dia,k.tipo) a
JOIN historico_setores h ON h.id=a.periodo_id AND h.emp_codigo=p.emp_codigo
LEFT JOIN setores_ergon e ON e.emp_codigo=h.emp_codigo AND e.setor=h.setor
 AND e.dtini<=p.dia AND (e.dtfim IS NULL OR e.dtfim>=p.dia)
LEFT JOIN LATERAL comando_organograma_em(h.emp_codigo,h.setor,p.dia,e.funcao_chefe_id,e.cargo_chefe_id) comando ON true;

COMMENT ON VIEW radar_organograma_chefias_ocupacao IS
