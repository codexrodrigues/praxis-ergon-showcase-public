-- Intervalos da projeção são divididos em cada alteração estrutural/paramétrica do órgão.
-- Uma mudança no pai também muda o caminho do filho, mesmo sem novo período no filho.
-- As quatro famílias de impedimento de PACK_ERGON.GET_CHF_EXERC são consultadas
-- por vínculo completo. Datas são efeitos dos assentamentos hoje conhecidos, não auditoria bitemporal.
CREATE VIEW organograma_impedimentos AS
 SELECT emp_codigo,numfunc,numvinc,id,'FERIAS'::text AS familia,dtini,
   LEAST(COALESCE(dtfim,dtprevfim),COALESCE(dt_interrupcao-1,COALESCE(dtfim,dtprevfim))) AS dtfim,1 AS prioridade
 FROM ferias_gozo WHERE situacao IN('HOMOLOGADA','EM_GOZO','GOZADA','INTERROMPIDA')
 UNION ALL
 SELECT emp_codigo,numfunc,numvinc,id,'LICENCA_ESPECIAL',dtini,COALESCE(dtfim,dtprevfim),2
 FROM licencas_especiais_gozo WHERE situacao IN('HOMOLOGADA','EM_GOZO','GOZADA','INTERROMPIDA')
 UNION ALL
 SELECT emp_codigo,numfunc,numvinc,id,'AFASTAMENTO',dtini,dtfim,3
 FROM afastamentos WHERE situacao='HOMOLOGADO'
 UNION ALL
 SELECT f.emp_codigo,f.numfunc,f.numvinc,f.id,'FREQUENCIA_AFASTADORA',f.dtini,COALESCE(f.dtfim,f.dtini),4
 FROM frequencias f JOIN codigos_frequencia c ON c.tipofreq=f.tipofreq AND c.codigo=f.codfreq
 WHERE f.situacao='HOMOLOGADO' AND c.afastamento;

-- Projeção da titularidade por função já representada no Slice 7. Cargo exige a autoridade
-- histórica de provimento/eventos, ainda não disponível; nesse caso o resultado é desconhecido.
CREATE FUNCTION comando_organograma_em(p_org INTEGER,p_setor VARCHAR,p_data DATE,p_funcao BIGINT,p_cargo INTEGER)
RETURNS TABLE(titular_numfunc BIGINT,titular_numvinc INTEGER,titular_nome VARCHAR,
 exercicio_numfunc BIGINT,exercicio_numvinc INTEGER,exercicio_nome VARCHAR,motivo TEXT,situacao TEXT)
LANGUAGE sql STABLE AS $$
 WITH funcao_vigente AS (
  SELECT f.id FROM funcoes_confianca f
  WHERE f.id=p_funcao AND f.emp_codigo=p_org AND p_cargo IS NULL
    AND f.dtini<=p_data AND (f.dtfim IS NULL OR f.dtfim>=p_data)
    AND f.situacao IN('ATIVA','EXTINTA')
 ), titulares AS (
  SELECT d.* FROM designacoes_funcao d JOIN funcao_vigente f ON f.id=d.funcao_id
  JOIN vinculos v ON v.numfunc=d.titular_numfunc AND v.numero=d.titular_numvinc AND v.emp_codigo=d.emp_codigo
  WHERE d.emp_codigo=p_org AND d.setor_id=p_setor AND d.funcao_id=p_funcao
    AND d.situacao IN('EM_EXERCICIO','DISPENSADA') AND d.dtini<=p_data AND d.dt_exercicio<=p_data
    AND (d.dtfim IS NULL OR d.dtfim>=p_data)
 ), cardinalidade AS (SELECT count(*) AS n FROM titulares), unico AS (
  SELECT d.* FROM titulares d CROSS JOIN cardinalidade c WHERE c.n=1
 ), ausencia AS (
  SELECT i.* FROM organograma_impedimentos i JOIN unico d ON d.emp_codigo=i.emp_codigo
    AND d.titular_numfunc=i.numfunc AND d.titular_numvinc=i.numvinc
  WHERE i.dtini<=p_data AND (i.dtfim IS NULL OR i.dtfim>=p_data)
 ), coberturas AS (
  SELECT s.* FROM substituicoes_funcao s JOIN unico d ON d.id=s.designacao_id AND d.emp_codigo=s.emp_codigo
  JOIN vinculos v ON v.numfunc=s.substituto_numfunc AND v.numero=s.substituto_numvinc AND v.emp_codigo=s.emp_codigo
  WHERE s.situacao IN('EM_EXERCICIO','PENDENTE_FOLHA','LIQUIDADA') AND p_data BETWEEN s.dtini AND s.dtfim
   AND (s.substituto_numfunc,s.substituto_numvinc)<>(d.titular_numfunc,d.titular_numvinc)
   AND EXISTS(SELECT 1 FROM ausencia i WHERE
       (i.familia='FERIAS' AND s.ferias_gozo_id=i.id AND s.afastamento_id IS NULL)
       OR (i.familia='AFASTAMENTO' AND s.afastamento_id=i.id AND s.ferias_gozo_id IS NULL))
   AND NOT EXISTS(SELECT 1 FROM organograma_impedimentos i WHERE i.emp_codigo=s.emp_codigo
       AND i.numfunc=s.substituto_numfunc AND i.numvinc=s.substituto_numvinc
       AND i.dtini<=p_data AND (i.dtfim IS NULL OR i.dtfim>=p_data))
 ), diagnostico AS (
  SELECT c.n,d.id,d.titular_numfunc,d.titular_numvinc,
   (SELECT familia FROM ausencia ORDER BY prioridade,id LIMIT 1) AS motivo,
   (SELECT count(*) FROM coberturas) AS coberturas,
   CASE WHEN p_funcao IS NULL AND p_cargo IS NULL THEN 'SEM_CHEFIA_PARAMETRIZADA'
    WHEN p_cargo IS NOT NULL THEN NULL
    WHEN NOT EXISTS(SELECT 1 FROM funcao_vigente) THEN NULL
    WHEN c.n>1 THEN 'CONFLITO_DUPLA_TITULARIDADE'
    WHEN c.n=0 THEN 'VACANCIA_CHEFIA_SEM_TITULAR'
    WHEN NOT EXISTS(SELECT 1 FROM ausencia) THEN 'TITULAR_EM_EXERCICIO'
    WHEN (SELECT count(*) FROM coberturas)=1 THEN 'SUBSTITUTO_EM_EXERCICIO_TITULAR_AUSENTE'
    WHEN (SELECT count(*) FROM coberturas)>1 THEN NULL -- ambiguidade interina não equivale a descobertura
    ELSE 'DESCOBERTURA_CRITICA_TITULAR_AUSENTE_SEM_SUBSTITUTO' END AS situacao
  FROM cardinalidade c LEFT JOIN unico d ON true
 ), resultado AS (
  SELECT d.*,CASE WHEN situacao='TITULAR_EM_EXERCICIO' THEN d.titular_numfunc
        WHEN situacao='SUBSTITUTO_EM_EXERCICIO_TITULAR_AUSENTE' THEN (SELECT substituto_numfunc FROM coberturas) END AS exercicio_numfunc,
   CASE WHEN situacao='TITULAR_EM_EXERCICIO' THEN d.titular_numvinc
        WHEN situacao='SUBSTITUTO_EM_EXERCICIO_TITULAR_AUSENTE' THEN (SELECT substituto_numvinc FROM coberturas) END AS exercicio_numvinc
  FROM diagnostico d
 ) SELECT r.titular_numfunc,r.titular_numvinc,t.nome,r.exercicio_numfunc,r.exercicio_numvinc,e.nome,r.motivo,r.situacao
 FROM resultado r LEFT JOIN funcionarios t ON t.numero=r.titular_numfunc
 LEFT JOIN funcionarios e ON e.numero=r.exercicio_numfunc;
$$;

CREATE VIEW radar_organograma_chefias_ocupacao AS
WITH limites AS (
 SELECT emp_codigo,dtini AS dia FROM historico_setores
