-- Uma linha por designação em exercício, com titularidade separada do exercício interino.
-- Tanto a busca de impedimentos quanto a de substituições usam a identidade do órgão.
CREATE VIEW radar_chefias_substituicoes AS
SELECT pos.id, pos.id AS designacao_id, pos.emp_codigo, pos.descricao, pos.funcao_id, pos.setor_id,
       pos.vaga_funcao_id, pos.titular_numfunc, pos.titular_numvinc, pos.dt_exercicio AS dtini, pos.dtfim,
       pos.custom_fields, CURRENT_DATE AS data_referencia, pos.afastamento_id, pos.ferias_gozo_id,
       pos.substituicao_id, pos.qtd_coberturas, pos.pendencias_folha,
       CASE WHEN pos.afastamento_id IS NULL AND pos.ferias_gozo_id IS NULL THEN 'TITULAR_EM_EXERCICIO'
            WHEN pos.substituicao_id IS NOT NULL THEN 'COBERTA'
            ELSE 'DESCOBERTA' END AS situacao
FROM (
  SELECT d.*,
      (SELECT a.id FROM afastamentos a
        WHERE a.emp_codigo = d.emp_codigo AND a.numfunc = d.titular_numfunc AND a.numvinc = d.titular_numvinc
          AND a.situacao = 'HOMOLOGADO' AND a.dtini <= CURRENT_DATE AND (a.dtfim IS NULL OR a.dtfim >= CURRENT_DATE)
        ORDER BY a.dtini DESC, a.id DESC FETCH FIRST 1 ROW ONLY) AS afastamento_id,
      (SELECT g.id FROM ferias_gozo g
        WHERE g.emp_codigo = d.emp_codigo AND g.numfunc = d.titular_numfunc AND g.numvinc = d.titular_numvinc
          AND g.situacao IN ('HOMOLOGADA', 'EM_GOZO', 'GOZADA', 'INTERROMPIDA')
          AND g.dtini <= CURRENT_DATE AND COALESCE(g.dtfim, g.dtprevfim) >= CURRENT_DATE
          AND (g.dt_interrupcao IS NULL OR g.dt_interrupcao > CURRENT_DATE)
        ORDER BY g.dtini DESC, g.id DESC FETCH FIRST 1 ROW ONLY) AS ferias_gozo_id,
      cobertura.id AS substituicao_id,
      COALESCE(cobertura.quantidade, 0) AS qtd_coberturas,
      (SELECT CAST(COUNT(*) AS INTEGER) FROM substituicoes_funcao s
        WHERE s.designacao_id = d.id AND s.emp_codigo = d.emp_codigo
          AND s.situacao = 'PENDENTE_FOLHA') AS pendencias_folha
  FROM designacoes_funcao d
  JOIN funcoes_confianca f ON f.id = d.funcao_id AND f.emp_codigo = d.emp_codigo
  LEFT JOIN (
    SELECT s.id, s.designacao_id, s.emp_codigo,
           CAST(COUNT(*) OVER (PARTITION BY s.emp_codigo, s.designacao_id) AS INTEGER) AS quantidade,
           ROW_NUMBER() OVER (
               PARTITION BY s.emp_codigo, s.designacao_id ORDER BY s.dtini DESC, s.id DESC
           ) AS ordem
    FROM substituicoes_funcao s
    JOIN designacoes_funcao titular ON titular.id = s.designacao_id AND titular.emp_codigo = s.emp_codigo
    WHERE s.situacao IN ('EM_EXERCICIO', 'PENDENTE_FOLHA', 'LIQUIDADA')
      AND CURRENT_DATE BETWEEN s.dtini AND s.dtfim
      AND (
        (s.ferias_gozo_id IS NULL AND EXISTS (
          SELECT 1 FROM afastamentos a
          WHERE a.id = s.afastamento_id AND a.emp_codigo = s.emp_codigo
            AND a.numfunc = titular.titular_numfunc AND a.numvinc = titular.titular_numvinc
            AND a.situacao = 'HOMOLOGADO' AND a.dtini <= CURRENT_DATE
            AND (a.dtfim IS NULL OR a.dtfim >= CURRENT_DATE)
        )) OR
        (s.afastamento_id IS NULL AND EXISTS (
          SELECT 1 FROM ferias_gozo g
          WHERE g.id = s.ferias_gozo_id AND g.emp_codigo = s.emp_codigo
            AND g.numfunc = titular.titular_numfunc AND g.numvinc = titular.titular_numvinc
            AND g.situacao IN ('HOMOLOGADA', 'EM_GOZO', 'GOZADA', 'INTERROMPIDA')
            AND g.dtini <= CURRENT_DATE AND COALESCE(g.dtfim, g.dtprevfim) >= CURRENT_DATE
            AND (g.dt_interrupcao IS NULL OR g.dt_interrupcao > CURRENT_DATE)
        ))
      )
  ) cobertura ON cobertura.designacao_id = d.id AND cobertura.emp_codigo = d.emp_codigo AND cobertura.ordem = 1
  WHERE d.situacao = 'EM_EXERCICIO' AND d.dt_exercicio <= CURRENT_DATE
    AND (d.dtfim IS NULL OR d.dtfim >= CURRENT_DATE)
    AND f.dtini <= CURRENT_DATE AND (f.dtfim IS NULL OR f.dtfim >= CURRENT_DATE)
    AND f.situacao <> 'EXTINTA'
    AND f.categoria IN ('DIRECAO', 'CHEFIA')
) pos;
