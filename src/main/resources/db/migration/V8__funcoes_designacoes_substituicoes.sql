CREATE TABLE funcoes_confianca (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  emp_codigo INTEGER NOT NULL,
  descricao VARCHAR(200) NOT NULL,
  dtini DATE NOT NULL,
  dtfim DATE,
  situacao VARCHAR(30) NOT NULL CHECK (situacao IN ('ATIVA', 'SUSPENSA', 'EXTINTA')),
  codigo VARCHAR(24) NOT NULL,
  categoria VARCHAR(24) NOT NULL CHECK (categoria IN ('DIRECAO', 'CHEFIA', 'ASSESSORAMENTO')),
  simbolo VARCHAR(20) NOT NULL,
  controle_vaga BOOLEAN NOT NULL,
  dt_inicio_contr_vaga DATE,
  permite_substituicao BOOLEAN NOT NULL,
  tipo_substituicao VARCHAR(50),
  dias_minimos_substituicao INTEGER,
  valor_gratificacao NUMERIC(15, 2) NOT NULL,
  percentual_opcao_efetivo NUMERIC(5, 2),
  exige_vinculo_efetivo BOOLEAN NOT NULL,
  requisitos VARCHAR(2000),
  documento_legal_id BIGINT,
  ato_publicacao_id BIGINT,
  observacoes VARCHAR(2000),
  custom_fields JSONB DEFAULT JSON '{}',
  version BIGINT NOT NULL DEFAULT 0,
  created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (emp_codigo) REFERENCES empresas(empresa),
  FOREIGN KEY (documento_legal_id) REFERENCES documentos_legais(id),
  FOREIGN KEY (ato_publicacao_id) REFERENCES documentos_legais(id),
  UNIQUE (id, emp_codigo),
  CHECK (dtfim IS NULL OR dtfim >= dtini),
  UNIQUE (emp_codigo, codigo),
  CHECK (valor_gratificacao >= 0),
  CHECK (percentual_opcao_efetivo BETWEEN 0 AND 100),
  CHECK (dias_minimos_substituicao >= 0)
);

CREATE TABLE vagas_funcao (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  emp_codigo INTEGER NOT NULL,
  descricao VARCHAR(200) NOT NULL,
  dtini DATE NOT NULL,
  dtfim DATE,
  situacao VARCHAR(30) NOT NULL CHECK (situacao IN ('LIVRE', 'OCUPADA', 'BLOQUEADA', 'EXTINTA')),
  numero_vaga BIGINT NOT NULL,
  funcao_id BIGINT NOT NULL,
  setor_id VARCHAR(30) NOT NULL,
  origem_vaga VARCHAR(50) NOT NULL,
  titular_atual_numfunc BIGINT,
  titular_atual_numvinc INTEGER,
  motivo_bloqueio VARCHAR(500),
  documento_legal_id BIGINT,
  ato_publicacao_id BIGINT,
  observacoes VARCHAR(2000),
  custom_fields JSONB DEFAULT JSON '{}',
  version BIGINT NOT NULL DEFAULT 0,
  created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (emp_codigo) REFERENCES empresas(empresa),
  FOREIGN KEY (funcao_id, emp_codigo) REFERENCES funcoes_confianca(id, emp_codigo),
  FOREIGN KEY (setor_id) REFERENCES setores(setor),
  FOREIGN KEY (titular_atual_numfunc, titular_atual_numvinc) REFERENCES vinculos(numfunc, numero),
  CHECK ((titular_atual_numfunc IS NULL) = (titular_atual_numvinc IS NULL)),
  FOREIGN KEY (documento_legal_id) REFERENCES documentos_legais(id),
  FOREIGN KEY (ato_publicacao_id) REFERENCES documentos_legais(id),
  UNIQUE (id, emp_codigo),
  CHECK (dtfim IS NULL OR dtfim >= dtini),
  UNIQUE (emp_codigo, numero_vaga),
  UNIQUE (id, emp_codigo, funcao_id),
  CHECK (numero_vaga BETWEEN 1 AND 999999999999)
);

CREATE TABLE designacoes_funcao (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  emp_codigo INTEGER NOT NULL,
  descricao VARCHAR(200) NOT NULL,
  dtini DATE NOT NULL,
  dtfim DATE,
  situacao VARCHAR(30) NOT NULL CHECK (situacao IN ('DESIGNADA', 'EM_EXERCICIO', 'SUSPENSA', 'DISPENSADA')),
  titular_numfunc BIGINT NOT NULL,
  titular_numvinc INTEGER NOT NULL,
  funcao_id BIGINT NOT NULL,
  vaga_funcao_id BIGINT,
  setor_id VARCHAR(30) NOT NULL,
  dt_exercicio DATE,
  substituto1_numfunc BIGINT,
  substituto1_numvinc INTEGER,
  substituto2_numfunc BIGINT,
  substituto2_numvinc INTEGER,
  opcao_remuneracao VARCHAR(24) NOT NULL CHECK (opcao_remuneracao IN ('INTEGRAL', 'VINCULO_EFETIVO')),
  valor_remuneracao NUMERIC(15, 2),
  ato_dispensa_id BIGINT,
  motivo_dispensa VARCHAR(500),
  documento_legal_id BIGINT,
  ato_publicacao_id BIGINT,
  observacoes VARCHAR(2000),
  custom_fields JSONB DEFAULT JSON '{}',
  version BIGINT NOT NULL DEFAULT 0,
  created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (emp_codigo) REFERENCES empresas(empresa),
  FOREIGN KEY (titular_numfunc, titular_numvinc) REFERENCES vinculos(numfunc, numero),
  FOREIGN KEY (funcao_id, emp_codigo) REFERENCES funcoes_confianca(id, emp_codigo),
  FOREIGN KEY (vaga_funcao_id, emp_codigo, funcao_id) REFERENCES vagas_funcao(id, emp_codigo, funcao_id),
  FOREIGN KEY (setor_id) REFERENCES setores(setor),
  FOREIGN KEY (substituto1_numfunc, substituto1_numvinc) REFERENCES vinculos(numfunc, numero),
  CHECK ((substituto1_numfunc IS NULL) = (substituto1_numvinc IS NULL)),
  FOREIGN KEY (substituto2_numfunc, substituto2_numvinc) REFERENCES vinculos(numfunc, numero),
  CHECK ((substituto2_numfunc IS NULL) = (substituto2_numvinc IS NULL)),
  FOREIGN KEY (ato_dispensa_id) REFERENCES documentos_legais(id),
  FOREIGN KEY (documento_legal_id) REFERENCES documentos_legais(id),
  FOREIGN KEY (ato_publicacao_id) REFERENCES documentos_legais(id),
  UNIQUE (id, emp_codigo),
  CHECK (dtfim IS NULL OR dtfim >= dtini),
  CHECK (dt_exercicio IS NULL OR (dt_exercicio >= dtini AND (dtfim IS NULL OR dt_exercicio <= dtfim))),
  CHECK (valor_remuneracao >= 0)
);

CREATE TABLE substituicoes_funcao (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  emp_codigo INTEGER NOT NULL,
  descricao VARCHAR(200) NOT NULL,
  dtini DATE NOT NULL,
  dtfim DATE NOT NULL,
  situacao VARCHAR(30) NOT NULL CHECK (situacao IN ('PROGRAMADA', 'EM_EXERCICIO', 'PENDENTE_FOLHA', 'LIQUIDADA', 'CANCELADA')),
  designacao_id BIGINT NOT NULL,
  substituto_numfunc BIGINT NOT NULL,
  substituto_numvinc INTEGER NOT NULL,
  motivo VARCHAR(24) NOT NULL CHECK (motivo IN ('FERIAS', 'AFASTAMENTO', 'AUSENCIA_EVENTUAL')),
  afastamento_id BIGINT,
  ferias_gozo_id BIGINT,
  dtini_remunerada DATE,
  dtfim_remunerada DATE,
  competencia_folha DATE,
  valor_substituicao NUMERIC(15, 2),
  documento_legal_id BIGINT,
  ato_publicacao_id BIGINT,
  observacoes VARCHAR(2000),
  custom_fields JSONB DEFAULT JSON '{}',
  version BIGINT NOT NULL DEFAULT 0,
  created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (emp_codigo) REFERENCES empresas(empresa),
  FOREIGN KEY (designacao_id, emp_codigo) REFERENCES designacoes_funcao(id, emp_codigo),
  FOREIGN KEY (substituto_numfunc, substituto_numvinc) REFERENCES vinculos(numfunc, numero),
  FOREIGN KEY (afastamento_id) REFERENCES afastamentos(id),
  FOREIGN KEY (ferias_gozo_id) REFERENCES ferias_gozo(id),
  FOREIGN KEY (documento_legal_id) REFERENCES documentos_legais(id),
  FOREIGN KEY (ato_publicacao_id) REFERENCES documentos_legais(id),
  UNIQUE (id, emp_codigo),
  CHECK (dtfim IS NULL OR dtfim >= dtini),
  CHECK (valor_substituicao >= 0),
  CHECK ((dtini_remunerada IS NULL AND dtfim_remunerada IS NULL)
      OR (dtini_remunerada IS NOT NULL AND dtfim_remunerada IS NOT NULL
          AND dtini_remunerada >= dtini AND dtfim_remunerada BETWEEN dtini_remunerada AND dtfim))
);

